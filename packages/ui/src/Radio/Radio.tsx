import { cx } from '@slurp-ui/utils';
import {
  createContext,
  useContext,
  useId,
  type ChangeEvent,
  type ElementType,
  type ReactNode,
} from 'react';

import { splitToggleProps, type ToggleInputAttributes } from '../Checkbox/Checkbox';
import { useAnimationRoot } from '../internal/animation';
import { useCss, useParts, useThemeProps } from '../internal/styled';
import type { PartsProps, PolymorphicProps } from '../lib/polymorphic';
import { useControlled } from '../utils/useControlled';

interface RadioGroupContextValue {
  name: string;
  value: string | null;
  setValue: (value: string) => void;
  disabled?: boolean;
}

const RadioGroupContext = createContext<RadioGroupContextValue | null>(null);

export interface RadioOwnProps
  extends Omit<ToggleInputAttributes, 'value'>, PartsProps<'input' | 'dot' | 'label'> {
  /** Submitted value; inside a RadioGroup, the value it selects. */
  value: string;
  /** Standalone use only (inside a RadioGroup the group decides). */
  checked?: boolean;
  onCheckedChange?: (checked: boolean) => void;
  children?: ReactNode;
}

export type RadioProps<E extends ElementType = 'label'> = PolymorphicProps<E, RadioOwnProps>;

/** Native radio: the checked one is an accent ring with a dot (a shape, not only colour). Use it in a RadioGroup. */
export function Radio<E extends ElementType = 'label'>(props: RadioProps<E>) {
  const {
    as,
    css,
    className,
    checked: checkedProp,
    onCheckedChange,
    children,
    parts,
    partProps,
    classNames,
    ...others
  } = useThemeProps('Radio', props as RadioProps);
  const { input, root: rest } = splitToggleProps(others);
  const group = useContext(RadioGroupContext);
  const value = input.value as string;
  const checked = group ? group.value === value : !!checkedProp;
  const disabled = (input.disabled as boolean | undefined) ?? group?.disabled;
  const Root = (as ?? 'label') as ElementType;
  const styled = useCss('Radio', 'root', css);
  const { part, style } = useParts('Radio', { parts, partProps, classNames });
  const root = useAnimationRoot(rest);
  return (
    <>
      {styled.style}
      {style}
      <Root
        className={cx('slurp-toggle', 'slurp-radio', styled.className, className)}
        data-state={checked ? 'on' : 'off'}
        data-disabled={disabled ? '' : undefined}
        {...root}
      >
        {part('input', 'input', {
          ...input,
          type: 'radio',
          name: (input.name as string | undefined) ?? group?.name,
          disabled,
          className: 'slurp-toggle-input',
          checked,
          onChange: (e: ChangeEvent<HTMLInputElement>) => {
            if (!e.target.checked) return;
            if (group) group.setValue(value);
            else onCheckedChange?.(true);
          },
        })}
        {part('dot', 'span', { className: 'slurp-radio-dot', 'aria-hidden': true })}
        {children != null && part('label', 'span', { className: 'slurp-toggle-label', children })}
      </Root>
    </>
  );
}

export interface RadioGroupOwnProps extends PartsProps<'legend'> {
  /** Name of the group (the fieldset's legend). */
  label: ReactNode;
  value?: string | null;
  defaultValue?: string | null;
  onValueChange?: (value: string) => void;
  /** Form name of the radios (generated by default). */
  name?: string;
  disabled?: boolean;
  /** Radios side by side. Default `vertical`. */
  orientation?: 'vertical' | 'horizontal';
  children?: ReactNode;
}

export type RadioGroupProps<E extends ElementType = 'fieldset'> = PolymorphicProps<
  E,
  RadioGroupOwnProps
>;

/** Single choice: a fieldset of native radios (arrow keys move and select, the legend names the group). */
export function RadioGroup<E extends ElementType = 'fieldset'>(props: RadioGroupProps<E>) {
  const {
    as,
    css,
    className,
    label,
    value: valueProp,
    defaultValue = null,
    onValueChange,
    name: nameProp,
    disabled,
    orientation = 'vertical',
    children,
    parts,
    partProps,
    classNames,
    ...rest
  } = useThemeProps('RadioGroup', props as RadioGroupProps);
  const [value, setValue] = useControlled<string | null>({
    value: valueProp,
    defaultValue,
    onChange: onValueChange as ((v: string | null) => void) | undefined,
  });
  const auto = useId();
  const Root = (as ?? 'fieldset') as ElementType;
  const styled = useCss('RadioGroup', 'root', css);
  const { part, style } = useParts('RadioGroup', { parts, partProps, classNames });
  const root = useAnimationRoot(rest);
  return (
    <>
      {styled.style}
      {style}
      <Root
        className={cx('slurp-radio-group', styled.className, className)}
        data-orientation={orientation}
        disabled={disabled}
        {...root}
      >
        {part('legend', 'legend', { className: 'slurp-radio-group-legend', children: label })}
        <RadioGroupContext value={{ name: nameProp ?? auto, value, setValue, disabled }}>
          {children}
        </RadioGroupContext>
      </Root>
    </>
  );
}
