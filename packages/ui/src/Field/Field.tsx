import { ErrorIcon } from '@slurp-ui/icons';
import { cx } from '@slurp-ui/utils';
import {
  useId,
  type ChangeEvent,
  type ElementType,
  type FocusEventHandler,
  type HTMLInputTypeAttribute,
  type KeyboardEventHandler,
  type ReactNode,
} from 'react';

import { useAnimationRoot } from '../internal/animation';
import { useCss, useParts, useThemeProps } from '../internal/styled';
import type { PartsProps, PolymorphicProps } from '../lib/polymorphic';
import { useControlled } from '../utils/useControlled';

/** Props that belong to the native input (the rest goes to the root, like every component). */
export interface InputAttributes {
  name?: string;
  type?: HTMLInputTypeAttribute;
  placeholder?: string;
  autoComplete?: string;
  autoFocus?: boolean;
  inputMode?: 'none' | 'text' | 'tel' | 'url' | 'email' | 'numeric' | 'decimal' | 'search';
  enterKeyHint?: 'enter' | 'done' | 'go' | 'next' | 'previous' | 'search' | 'send';
  maxLength?: number;
  minLength?: number;
  pattern?: string;
  readOnly?: boolean;
  required?: boolean;
  disabled?: boolean;
  spellCheck?: boolean;
  onBlur?: FocusEventHandler<HTMLInputElement | HTMLTextAreaElement>;
  onFocus?: FocusEventHandler<HTMLInputElement | HTMLTextAreaElement>;
  onKeyDown?: KeyboardEventHandler<HTMLInputElement | HTMLTextAreaElement>;
}

const INPUT_KEYS = [
  'name',
  'type',
  'placeholder',
  'autoComplete',
  'autoFocus',
  'inputMode',
  'enterKeyHint',
  'maxLength',
  'minLength',
  'pattern',
  'readOnly',
  'required',
  'disabled',
  'spellCheck',
  'onBlur',
  'onFocus',
  'onKeyDown',
] as const;

/** Splits the native input's props from the root's. */
export function splitInputProps<P extends object>(props: P) {
  const input: Record<string, unknown> = {};
  const root: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(props)) {
    if ((INPUT_KEYS as readonly string[]).includes(k)) input[k] = v;
    else root[k] = v;
  }
  return { input, root };
}

export interface FieldOwnProps
  extends InputAttributes, PartsProps<'label' | 'control' | 'hint' | 'error'> {
  /** Visible label (always: placeholders are not labels). */
  label: ReactNode;
  /** Help text under the field, linked with aria-describedby. */
  hint?: ReactNode;
  /** Error message: marks the field invalid and shows the message with an icon. */
  error?: ReactNode;
  value?: string;
  defaultValue?: string;
  onValueChange?: (
    value: string,
    event: ChangeEvent<HTMLInputElement | HTMLTextAreaElement>,
  ) => void;
  /** A textarea instead of an input. */
  multiline?: boolean;
  /** Rows of the textarea. Default 3. */
  rows?: number;
  /** id of the input (generated by default). */
  id?: string;
}

export type FieldProps<E extends ElementType = 'div'> = PolymorphicProps<E, FieldOwnProps>;

/** Text field: label, input (boundary `border-control`, 3:1), hint and error, wired for assistive tech. */
export function Field<E extends ElementType = 'div'>(props: FieldProps<E>) {
  const {
    as,
    css,
    className,
    label,
    hint,
    error,
    value: valueProp,
    defaultValue = '',
    onValueChange,
    multiline = false,
    rows = 3,
    id: idProp,
    parts,
    partProps,
    classNames,
    ...others
  } = useThemeProps('Field', props as FieldProps);
  const { input, root: rest } = splitInputProps(others);
  const [value, setValue] = useControlled({ value: valueProp, defaultValue, onChange: undefined });
  const auto = useId();
  const id = idProp ?? `${auto}-input`;
  const hintId = hint != null ? `${auto}-hint` : undefined;
  const errorId = error != null && error !== false ? `${auto}-error` : undefined;
  const Root = (as ?? 'div') as ElementType;
  const styled = useCss('Field', 'root', css);
  const { part, style } = useParts('Field', { parts, partProps, classNames });
  const root = useAnimationRoot(rest);
  return (
    <>
      {styled.style}
      {style}
      <Root
        className={cx('slurp-field', styled.className, className)}
        data-invalid={errorId ? '' : undefined}
        data-disabled={input.disabled ? '' : undefined}
        {...root}
      >
        {part('label', 'label', { htmlFor: id, className: 'slurp-field-label', children: label })}
        {part('control', multiline ? 'textarea' : 'input', {
          ...input,
          id,
          rows: multiline ? rows : undefined,
          type: multiline ? undefined : (input.type ?? 'text'),
          className: 'slurp-field-control',
          value,
          'aria-invalid': errorId ? true : undefined,
          'aria-describedby': cx(errorId, hintId) || undefined,
          onChange: (e: ChangeEvent<HTMLInputElement | HTMLTextAreaElement>) => {
            setValue(e.target.value);
            onValueChange?.(e.target.value, e);
          },
        })}
        {hintId && part('hint', 'p', { id: hintId, className: 'slurp-field-hint', children: hint })}
        {errorId &&
          part('error', 'p', {
            id: errorId,
            className: 'slurp-field-error',
            children: (
              <>
                <ErrorIcon size={16} />
                <span>{error}</span>
              </>
            ),
          })}
      </Root>
    </>
  );
}
